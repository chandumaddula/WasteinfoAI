"""User and role models.

Each user carries exactly one role. Role checks are performed on the server side
in the authorization layer; the client role claim is never trusted.
"""
from __future__ import annotations

import datetime
import enum
import uuid

from sqlalchemy import Boolean, ForeignKey, String, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base


class UserRole(str, enum.Enum):
    """Supported application roles.

    * RESIDENT: submit waste reports, view own reports.
    * INSTITUTION: submit waste reports, view reports from authorized institution members.
    * REVIEWER: review, verify, reject, and mark reports as duplicates.
    * SANITATION_WORKER: view assigned tasks, submit permitted task updates.
    * ADMIN: perform authorized administrative operations.
    """

    RESIDENT = "RESIDENT"
    INSTITUTION = "INSTITUTION"
    REVIEWER = "REVIEWER"
    SANITATION_WORKER = "SANITATION_WORKER"
    ADMIN = "ADMIN"


class User(Base):
    """Application user.

    Client-supplied ``role`` and ``user_id`` are never used to establish identity or
    permissions; both are derived from the authenticated session.
    """

    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(String(36), primary_key=True, default=uuid.uuid4)
    email: Mapped[str] = mapped_column(String(255), unique=True, nullable=False, index=True)
    password_hash: Mapped[str | None] = mapped_column(String(255), nullable=True, default=None)
    role: Mapped[UserRole] = mapped_column(String(20), nullable=False, default=UserRole.RESIDENT)
    institution_id: Mapped[uuid.UUID | None] = mapped_column(
        String(36), ForeignKey("institutions.id"), nullable=True, default=None, index=True
    )
    full_name: Mapped[str | None] = mapped_column(String(128), nullable=True, default=None)
    display_name: Mapped[str | None] = mapped_column(String(64), nullable=True, default=None)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    created_at: Mapped[datetime.datetime] = mapped_column(
        default=datetime.datetime.now(datetime.timezone.utc), nullable=False, index=True
    )
    updated_at: Mapped[datetime.datetime] = mapped_column(
        default=datetime.datetime.now(datetime.timezone.utc),
        onupdate=datetime.datetime.now(datetime.timezone.utc),
        nullable=False,
    )

    # One user can be a member of one institution (if the feature is enabled).
    institution: Mapped["Institution | None"] = relationship(
        "Institution", back_populates="members", lazy="joined", uselist=False
    )

    # Reports owned by this user.
    reports: Mapped[list["Report"]] = relationship(
        "Report", back_populates="owner", lazy="selectin"
    )

    def __repr__(self) -> str:
        return f"<User(id={self.id!r} email={self.email!r} role={self.role.value!r})>"


class UserToken(Base):
    """Bearer token issued to a user for authentication.

    Tokens are UUID4 values generated by the server. They are stored as UUIDs (not
    hashed) because they have high entropy; in a production deployment you would
    hash tokens before storage. Only active tokens are accepted.

    A user may hold multiple tokens; each token has an optional expiration.
    """

    __tablename__ = "user_tokens"

    id: Mapped[uuid.UUID] = mapped_column(String(36), primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(
        String(36), ForeignKey("users.id"), nullable=False, index=True
    )
    token: Mapped[uuid.UUID] = mapped_column(String(36), nullable=False, unique=True, index=True)
    expires_at: Mapped[datetime.datetime | None] = mapped_column(
        nullable=True, default=None
    )
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    created_at: Mapped[datetime.datetime] = mapped_column(
        default=datetime.datetime.now(datetime.timezone.utc), nullable=False
    )
    last_used_at: Mapped[datetime.datetime | None] = mapped_column(
        nullable=True, default=None
    )

    __table_args__ = (
        # Each user can have at most one active token per label, supporting
        # scenarios like "web session" or "mobile session".
        UniqueConstraint("user_id", "token", name="uq_user_tokens_user_id_token"),
    )

    user: Mapped["User"] = relationship("User", lazy="joined")

    def __repr__(self) -> str:
        return f"<UserToken(user_id={self.user_id!r})>"


